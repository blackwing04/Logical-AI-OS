def load(name: str):
	p = HERE / "outputs" / name
	return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def mcnemar_p(b: int, c: int):
	from math import comb
	n = b + c
	return None if not n else min(1.0, 2 * sum(comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n)


def fp(p) -> str:
	return "—" if p is None else ("%.4f" % p if p >= 0.0001 else "<0.0001")


def ratio(b: int, c: int) -> str:
	return "inf" if c == 0 and b else ("—" if not b and not c else "%.2f" % (b / c))


def write_csv(name: str, head: list[str], rows: list[list]):
	buf = io.StringIO()
	w = csv.writer(buf, lineterminator="\n")
	w.writerow(head)
	w.writerows(rows)
	(OUT / name).write_text(buf.getvalue(), encoding="utf-8", newline="\n")


