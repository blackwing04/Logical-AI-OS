from __future__ import annotations

import re

# ① 感知提示詞（V2 欄序 ＋ 甲-2 短語指認）
PROMPT_SENSE = (
	"任務:{任務}\n"
	"句子:「{句子}」\n"
	"照以下四行格式回答,每欄一行,四行都要寫,不要多寫任何字:\n"
	"判定:是或否或不確定\n"
	"理由:B 怎麼影響 A,一句話\n"
	"A:任務裡會被影響的部分,限20字內,沒有就寫無\n"
	"B:這個句子的重點,限20字內,沒有就寫無"
)

# ④ 摺疊提示詞（吃結構化欄位，不吃自由散文）
PROMPT_FOLD = (
	"任務:{任務}\n"
	"句子:「{句子}」\n"
	"判定:{判定}\n"
	"理由:{理由}\n"
	"A:{A}\n"
	"B:{B}\n"
	"這句話對完成該任務是否構成必須遵守的條件?請只回答:是或否。"
)

# ③ 濾網槽讀的前綴：餵到這裡，讀下一個 token 的分佈
SLOT_PREFIX = "判定:"

FIELDS = ("判定", "理由", "A", "B")
# ② 固定槽讀取：逐行比欄名。**不在自由文字上掃正則**，濾網正則因此退休。
_FIELD_RE = re.compile(r"^(判定|理由|A|B)[::]\s*(.*)$")
VERDICT_HEADS = ("是", "否", "不")
AB_MAX = 20  # 甲-2：每欄 ≤20 字，不整段複製原文

# 甲-1 保底案（簽核令 §一.3、§二.4）：A/B 改回全文照寫。
# ＝簽核的 V2 原文**去掉**「限20字內」，其餘一字不動。
PROMPT_SENSE_FULL = PROMPT_SENSE.replace(",限20字內", "")
assert "限20字內" not in PROMPT_SENSE_FULL and PROMPT_SENSE_FULL != PROMPT_SENSE


def parse_slots(text: str) -> dict:
	"""固定槽讀取器。同欄重複出現時取第一次，缺欄就是缺欄，不猜。"""
	out: dict[str, str] = {}
	for line in text.splitlines():
		m = _FIELD_RE.match(line.strip())
		if m and m.group(1) not in out:
			out[m.group(1)] = m.group(2).strip()
	return out


def slot_health(slots: dict) -> dict:
	"""格式健檢：四欄齊否、判定欄首字合法否、A/B 是否逾 20 字。

	逾字**只記不改**——截斷會動到中間產物，而簽核令把審計定為
	「以指認對照原文」，所以逾字是要被看見的，不是被藏起來的。
	"""
	miss = [f for f in FIELDS if f not in slots]
	head = slots.get("判定", "")[:1]
	over = {f: len(slots.get(f, "")) for f in ("A", "B") if len(slots.get(f, "")) > AB_MAX}
	return {"四欄齊": not miss, "缺欄": miss,
	        "判定欄首字": head, "判定合法": head in VERDICT_HEADS,
	        "AB逾字": over}


def adapter_vote(verdict_head: str) -> str:
	"""濾網票：把判定欄首字映射回凍結版的「有／無」票型。

	凍結版是 `「第一句:無」→ 無票，其餘 → 有票`。所以：
	  `否` → 無（明確說沒有影響關係，等同凍結版的「無」）
	  `是` → 有
	  `不` → **有**——凍結版的正則只認「無」，任何不是「無」的輸出都算有票，
	         所以把「不確定」映射到有票才是**保持既有語義**；
	         映射到無票會讓濾網變嚴，那是改判準不是改格式。
	         本映射在報告中明列，供覆核。
	"""
	return "無" if verdict_head == "否" else "有"
