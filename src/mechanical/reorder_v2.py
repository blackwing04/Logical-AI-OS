# --- 終測案一（PI 2026-09-18，一發制）：描述框「我－領屬」例外 ---
# 第三方主語**且**帶「我＋親屬／領屬詞」構式 → 不入描述框，視同自陳。
# 依據：三修報告量到描述框丟的 5 句裡有 3 句帶「第一人稱＋親屬名詞」構式（**實例已去語料**）——
# 第三方主語抓到的是**話題**，而使用者的限制常掛在自己的親屬身上。
# **零新詞條**：構式用的是人稱偵測器既有的 `領屬複合`（第一人稱＋關係名詞閉集 38 詞，
# 該表已簽核，出處見 lexicon_v2.PERSON），本案不新增任何一個詞。
CASE1_POSSESSIVE_EXCEPTION = True

# F2（2026-10-05 規則對齊修正令 §二 F2）：描述框條件由「有第三方主語」
# 改為「主語非第一人稱」。旗標分開，迴歸 off／on 同次執行。
F2_DESCRIPTIVE_NON_FIRST = True   # 2026-10-06 F2/F4 裁決令：採用
# F2 的作用域：令文把條件寫在**描述框**上（描述框是子句級的框），
# 但驗收線「F1／F2 動到句中帶第一人稱者應為 0」是**句級**的。
# 兩者不一致——子句級跑出來有 27 句帶第一人稱被動到（該句別的子句有「我」）。
# 所以把作用域做成旗標，兩種都量，**不由 CC 挑**：
#   "clause"   ——照令文字面（條件寫在子句級的框上）
#   "sentence" ——照驗收線（整句有第一人稱就不套 F2 的放寬）
F2_SCOPE = "sentence"   # **PI 裁：句級**（人稱是句級性質；子句級讀法廢）

# ── F2-WS 寫作規格形豁免（2026-10-06 F2豁免與卷七gold前置令 §①）────────────
# 令文：「**F2 描述框掛同一張寫作規格形豁免表**（無第一人稱代理住兩處，
#        令文漏補為聊天端之誤；按語義族比，source=v2_writing_spec）。」
#
# 立案於卷六 G54：F1-WS 把「（不少於600字）」從篇級材料放出來之後，它立刻
# 落進**描述框**（主語非第一人稱＋敘述＋非過去）→ 表五照樣不進場 → 軸二仍材料。
# 「無第一人稱」這個代理在 F1 與 F2 兩處各有一份，只補一處等於沒補。
#
# **按族比，不按字面比**：表五寫作規格形有四條是「式」（`N字`／`N個字`／
# `N段`／`N句`），偵測器吐的是代入後的 `600字`，拿它比表鍵永遠不中。
# cue 自帶 `source="v2_writing_spec"` 就是族標。零新增詞——族的成員由簽核表決定。
F2_WS_EXEMPT = True
_WS_SOURCE = "v2_writing_spec"


def _ws_cues(sig: dict) -> list[str]:
	"""這個（子句的）訊號裡命中的寫作規格形，回報用樣式或字面。"""
	return [c.get("詞形") or c["cue"] for c in sig["限制形狀"]["cues"]
	        if c.get("source") == _WS_SOURCE]


def frame_and_axis2(a1: str, sig: dict, sent_has_first: bool = False) -> dict:
	"""重排版軸二。**先定框架，框架決定表五進不進場。**"""
	# 1 主請求框
	if a1 == "主請求":
		return {"框架": "主請求框", "表五": "不進場", "軸二": "無",
		        "表五命中": [], "依據": "軸一＝主請求（規則1照舊）"}
	# 2 過去敘事框
	if sig["時間"]["標籤"] == "過去" and sig["語氣"]["標籤"] == "敘述":
		return {"框架": "過去敘事框", "表五": "不進場", "軸二": "材料",
		        "表五命中": [], "依據": "時間錨＝過去 且 語氣＝敘述"}
	# 3、4 兩框都讓表五進場——**這裡才是表五第一次被允許掃描**
	cues = [c["cue"] for c in sig["限制形狀"]["cues"]]
	if sig["引述"]["命中"]:
		return {"框架": "引述框", "表五": "進場",
		        "軸二": "限制" if cues else "材料", "表五命中": cues,
		        "依據": "引述框命中：%s" % "／".join(
			        [h["term"] for h in sig["引述"]["轉述框"] + sig["引述"]["傳聞"]])}
	# 4 其餘框拆二（修三，PI 2026-09-18）
	# 回歸卷缺口：最小對立句非限制側 12 句全是**現在式描述**，過去敘事框要求時間錨＝過去，
	# 接不到它們，落進其餘框讓表五進場 → 量詞命中 → 誤判限制。
	# 分流依據是既有人稱偵測器：**第三方主語＋敘述＋非過去＝描述框**，表五不進場。
	# **令文寫「第一人稱／無主 → 自陳情境（照舊進場）」，所以「沒掛人」照舊進場。**
	# 這一點我照令文字面實作、不自行擴張：非限制側 12 句裡有 6 句帶**指示／概念主語**
	#（**實例已去語料**），人稱偵測器判「沒掛人」而非第三方，故本表接不到——證據見報告。
	# ── F2（2026-10-05 規則對齊修正令 §二 F2，PI 簽）────────────────────────
	# 令文：「條件改為『**主語非第一人稱**（含事物／指示／概念主語與無主）且敘述且非過去』
	#        → 描述框不進場；我-領屬例外照留。**人稱偵測器「沒掛人」不再等同自陳。**」
	#
	# 修正的是上一版的**令文走樣**：舊條件用 `有第三方主語`，而人稱偵測器對
	# 指示／概念主語（**實例已去語料**）會被回報為「沒掛人」，描述框接不到
	# （審計 D2，影響 98 子句／76 句）。
	#
	# **「你」的歸屬令文未明示，CC 標明為解讀點**：令文的括號列的是
	# 「事物／指示／概念主語與無主」，沒提第二人稱；但「你」字面上也非第一人稱。
	# 本檔取**字面**（非第一人稱即入描述框條件），並在迴歸報告單獨列出
	# 因「你」而改判的句數，供裁。
	_f2 = F2_DESCRIPTIVE_NON_FIRST and not (
		F2_SCOPE == "sentence" and sent_has_first)
	if _f2:
		not_first = not sig["人稱"]["我"]          # 第一人稱 scan 無命中（領屬複合由下方例外處理）
		cond = (not_first and sig["語氣"]["標籤"] == "敘述"
		        and sig["時間"]["標籤"] != "過去"
		        and not (CASE1_POSSESSIVE_EXCEPTION and sig["人稱"]["領屬複合"]))
		why = "主語非第一人稱＋敘述＋非過去（F2）"
	else:
		cond = (sig["人稱"]["有第三方主語"] and sig["語氣"]["標籤"] == "敘述"
		        and sig["時間"]["標籤"] != "過去"
		        and not (CASE1_POSSESSIVE_EXCEPTION and sig["人稱"]["領屬複合"]))
		why = "第三方主語＋敘述＋非過去"
	# F2-WS：描述框的豁免口。命中寫作規格形者**不入描述框**，照舊進場。
	# 放在 `cond` 之後、回傳之前——擋的是「已經判定要進描述框」的那些句子。
	_ws = _ws_cues(sig) if (F2_WS_EXEMPT and cond) else []
	if cond and _ws:
		return {"框架": "自陳情境（F2 規格形豁免）", "表五": "進場",
		        "軸二": "限制" if cues else "材料", "表五命中": cues,
		        "依據": "%s，但命中寫作規格形 %s → 不入描述框（F2-WS）"
		                % (why, "／".join(_ws)),
		        "F2豁免_寫作規格形": _ws}
	if cond:
		return {"框架": "描述框", "表五": "不進場", "軸二": "材料",
		        "表五命中": [], "依據": why}
	return {"框架": "自陳情境", "表五": "進場",
	        "軸二": "限制" if cues else "材料", "表五命中": cues,
	        "依據": "第一人稱／無主"}


def classify(units: list[dict]) -> list[dict]:
	"""整組句子跑重排版。units: [{sid, text}]。模型戶停用，故不吃 ask_fn。"""
	out = []
	for i, u in enumerate(units):
		later = [v["text"] for v in units[i + 1:]]
		sig = P.signals(u["text"], later)
		a1, r1 = P.axis1(sig, u["text"])
		a2 = frame_and_axis2(a1, sig)
		out.append({"sid": u["sid"], "sentence": u["text"],
		            "軸一": a1, "軸一規則": r1, **a2,
		            "語氣": sig["語氣"]["標籤"], "時間": sig["時間"]["標籤"],
		            "人稱": sig["人稱"]["標籤"],
		            "引述": bool(sig["引述"]["命中"]),
		            "裸掃表五命中": [c["cue"] for c in sig["限制形狀"]["cues"]]})
	return out
